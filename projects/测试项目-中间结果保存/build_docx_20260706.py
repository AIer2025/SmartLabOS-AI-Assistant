def table(headers, rows, widths=None, fontsize=9, header_fill=HDR_FILL,
          header_color=INK, caption=None):
    if caption:
        para(caption, size=9.5, bold=True, color=BRAND, before=4, after=2)
    ncol = len(headers)
    t = doc.add_table(rows=1, cols=ncol)
    t.style = 'Table Grid'
